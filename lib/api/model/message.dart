class Message {
  final String id;
  final String firstname;
  final String lastname;
  final String email;
  final String phone;
  final String subject;
  final String message;

  const Message({
    required this.id,
    required this.firstname,
    required this.lastname,
    required this.email,
    required this.phone,
    required this.subject,
    required this.message,
  });
}
