class Certification {
  final String id;
  final String name;
  final String title;
  final String issuer;
  final String dateEarned;
  final String credentialId;
  final String icon;

  const Certification({
    required this.id,
    required this.name,
    required this.title,
    required this.issuer,
    required this.dateEarned,
    required this.credentialId,
    required this.icon,
  });
}
